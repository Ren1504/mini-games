/** "Mission: Impossible" → "mission-impossible" (accents dropped). */
const slug = (s: string) =>
  s
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");

export const IMPOSTER_WORDS: readonly ImposterWord[] = (
  Object.entries(BANK) as Array<[WordCategory, readonly Row[]]>
).flatMap(([category, rows]) =>
  rows.map(([word, imposterClue, difficulty]) => ({
    id: `${slug(category)}-${slug(word)}`,
    word,
    category,
    imposterClue,
    difficulty,
  })),
);
